-- MiSai Development Hub - activity / notes log
-- Safe migration. Adds an authenticated shared activity log.

create table if not exists public.activity_log (
  id bigint generated by default as identity primary key,
  actor text,
  action text not null,
  entity_type text,
  entity_label text,
  details text,
  created_at timestamptz default now()
);

alter table public.activity_log enable row level security;
grant select, insert, update, delete on table public.activity_log to authenticated;

drop policy if exists "auth activity log" on public.activity_log;
create policy "auth activity log"
on public.activity_log
for all to authenticated
using (true)
with check (true);
