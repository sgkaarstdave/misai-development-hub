create table if not exists public.supplier_scores (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers(id) on delete cascade,
  quality numeric check (quality between 1 and 10),
  communication numeric check (communication between 1 and 10),
  speed numeric check (speed between 1 and 10),
  price numeric check (price between 1 and 10),
  moq_flexibility numeric check (moq_flexibility between 1 and 10),
  flexibility numeric check (flexibility between 1 and 10),
  reproducibility numeric check (reproducibility between 1 and 10),
  notes text,
  updated_at timestamptz default now(),
  unique (supplier_id)
);

create table if not exists public.cost_scenarios (
  id bigint generated by default as identity primary key,
  name text not null,
  supplier_id bigint references public.suppliers(id) on delete set null,
  product text,
  colorway text,
  quantity integer not null default 25,
  unit_cost numeric not null default 0,
  shipping numeric not null default 0,
  duties numeric not null default 0,
  tax numeric not null default 0,
  packaging numeric not null default 0,
  payment_fees numeric not null default 0,
  other_costs numeric not null default 0,
  sell_price numeric,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.sample_test_tasks (
  id bigint generated by default as identity primary key,
  sample_id bigint not null references public.samples(id) on delete cascade,
  task_type text not null,
  title text not null,
  target_count integer not null default 1,
  completed_count integer not null default 0,
  notes text,
  created_at timestamptz default now(),
  unique (sample_id, task_type)
);

alter table public.supplier_scores enable row level security;
alter table public.cost_scenarios enable row level security;
alter table public.sample_test_tasks enable row level security;

grant select, insert, update, delete on table public.supplier_scores to authenticated;
grant select, insert, update, delete on table public.cost_scenarios to authenticated;
grant select, insert, update, delete on table public.sample_test_tasks to authenticated;

drop policy if exists "auth supplier scores" on public.supplier_scores;
create policy "auth supplier scores" on public.supplier_scores
for all to authenticated using (true) with check (true);

