insert into public.sample_test_tasks (sample_id, task_type, title, target_count)
select s.id, x.task_type, x.title, x.target_count
from public.samples s
cross join (
  values
    ('wear', '3 Trainingseinheiten', 3),
    ('wash', '3 Waschgänge', 3),
    ('sweat', 'Schweiß-/Nass-Test', 1),
    ('fit', 'Fit & Bewegungsfreiheit prüfen', 1),
    ('review', 'Finales Review abgeben', 1)
) as x(task_type, title, target_count)
on conflict (sample_id, task_type) do nothing;

