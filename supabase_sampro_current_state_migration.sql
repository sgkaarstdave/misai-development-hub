-- Replace the older SAMPRO bulk tiers with the revised quotation dated 2026-11-16.
delete from public.supplier_price_tiers
where supplier_id in (select id from public.suppliers where lower(name) like '%sampro%')
  and currency = 'USD'
  and quantity in (25,50,100,250);

insert into public.supplier_price_tiers
(supplier_id, quantity, unit_price, currency, product_type, incoterm, notes)
select s.id, v.quantity, v.unit_price, 'USD', 'MiSai Performance Shirt', 'EXW Sialkot',
       'Revised indicative quotation dated 2026-11-16. Includes standard production, main fabric, sublimation, branding, labels/tag card and custom printed polybag. Shipping/import not included.'
from public.suppliers s
cross join (values
  (25, 16.00::numeric),
  (50, 14.75::numeric),
  (100, 13.60::numeric),
  (250, 12.25::numeric)
) as v(quantity, unit_price)
where lower(s.name) like '%sampro%'
on conflict do nothing;

