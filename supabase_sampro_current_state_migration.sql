create table if not exists public.supplier_profiles (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null unique references public.suppliers(id) on delete cascade,
  preferred_fabric text,
  composition text,
  gsm text,
  print_method text,
  fit_target text,
  included_items text,
  packaging_notes text,
  artwork_requirements text,
  construction_notes text,
  incoterm text,
  quote_date date,
  shipping_notes text,
  customs_notes text,
  sample_lead_time text,
  bulk_lead_time text,
  next_requirements text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.supplier_profiles enable row level security;
grant select, insert, update, delete on table public.supplier_profiles to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists "auth supplier profiles" on public.supplier_profiles;
create policy "auth supplier profiles"
on public.supplier_profiles
for all to authenticated
using (true)
with check (true);

