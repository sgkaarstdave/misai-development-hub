create table if not exists public.marketing_video_ideas (
  id bigint generated by default as identity primary key,
  title text not null,
  idea text not null,
  platform text not null default 'Instagram + TikTok',
  status text not null default 'Idee',
  rating numeric check (rating is null or (rating >= 1 and rating <= 5)),
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.marketing_video_ideas enable row level security;

drop policy if exists "Authenticated users can read marketing video ideas" on public.marketing_video_ideas;
create policy "Authenticated users can read marketing video ideas"
on public.marketing_video_ideas for select
to authenticated
using (true);

drop policy if exists "Authenticated users can create marketing video ideas" on public.marketing_video_ideas;
create policy "Authenticated users can create marketing video ideas"
on public.marketing_video_ideas for insert
to authenticated
with check (true);

drop policy if exists "Authenticated users can update marketing video ideas" on public.marketing_video_ideas;
create policy "Authenticated users can update marketing video ideas"
on public.marketing_video_ideas for update
to authenticated
using (true)
with check (true);

drop policy if exists "Authenticated users can delete marketing video ideas" on public.marketing_video_ideas;
create policy "Authenticated users can delete marketing video ideas"
on public.marketing_video_ideas for delete
to authenticated
using (true);
