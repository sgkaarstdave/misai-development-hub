create table if not exists public.fit_measurements (
  id bigint generated by default as identity primary key,
  person_name text not null,
  sample_id bigint not null references public.samples(id) on delete cascade,

  body_height numeric,
  body_weight numeric,
  body_chest numeric,
  body_belly numeric,
  body_shoulder numeric,

  shirt_chest numeric,
  shirt_belly numeric,
  shirt_hem numeric,
  shirt_length numeric,
  shirt_shoulder numeric,
  shirt_sleeve numeric,
  shirt_sleeve_opening numeric,

  fit_chest text,
  fit_belly text,
  fit_shoulders text,
  fit_sleeve text,
  fit_sleeve_length text,
  fit_length text,

  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.fit_measurements enable row level security;

drop policy if exists "Authenticated users can read fit measurements" on public.fit_measurements;
create policy "Authenticated users can read fit measurements"
on public.fit_measurements for select
to authenticated
using (true);

drop policy if exists "Authenticated users can create fit measurements" on public.fit_measurements;
create policy "Authenticated users can create fit measurements"
on public.fit_measurements for insert
to authenticated
with check (true);

drop policy if exists "Authenticated users can update fit measurements" on public.fit_measurements;
create policy "Authenticated users can update fit measurements"
on public.fit_measurements for update
to authenticated
using (true)
with check (true);

drop policy if exists "Authenticated users can delete fit measurements" on public.fit_measurements;
create policy "Authenticated users can delete fit measurements"
on public.fit_measurements for delete
to authenticated
using (true);

grant select, insert, update, delete
on table public.fit_measurements
to authenticated;

grant usage, select
on all sequences in schema public
to authenticated;

notify pgrst, 'reload schema';
