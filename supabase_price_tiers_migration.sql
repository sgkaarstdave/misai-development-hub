-- MiSai Development Hub - structured supplier price tiers
-- Run once in Supabase SQL Editor. Safe to run again.

create table if not exists public.supplier_price_tiers (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers(id) on delete cascade,
  quantity integer not null check (quantity > 0),
  unit_price numeric not null check (unit_price >= 0),
  currency text not null default 'EUR',
  product_type text,
  incoterm text,
  notes text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create unique index if not exists supplier_price_tiers_unique
on public.supplier_price_tiers
(supplier_id, quantity, coalesce(product_type,''), coalesce(currency,''));

alter table public.supplier_price_tiers enable row level security;
grant select, insert, update, delete on table public.supplier_price_tiers to authenticated;

drop policy if exists "auth supplier price tiers" on public.supplier_price_tiers;
create policy "auth supplier price tiers"
on public.supplier_price_tiers
for all to authenticated
using (true)
with check (true);

-- SAMPRO Sports - known bulk indicative EXW pricing
insert into public.supplier_price_tiers
(supplier_id, quantity, unit_price, currency, product_type, incoterm, notes)
select s.id, v.quantity, v.unit_price, 'USD', 'Performance T-Shirt', 'EXW',
       'Bulk indicative pricing from manufacturer.'
from public.suppliers s
cross join (values
  (25, 14.50::numeric),
  (50, 13.00::numeric),
  (100, 11.80::numeric),
  (250, 10.50::numeric)
) as v(quantity, unit_price)
where lower(s.name) like '%sampro%'
on conflict do nothing;

